p("Серверная автоматика работает параллельно API: каждые 2 секунды проверяются "
  "пороги и выполняются правила — полив при низкой влажности, проветривание при "
  "перегреве, досветка по уровню света. Импульсные запуски управляются таймерами "
  "(поле remaining в API), есть защита от работы при пустом баке и повтор "
  "предупреждений в журнале не чаще заданного интервала.")

h2("7.4. Работа с датчиками через Arduino")

p("Датчики и исполнители подключены к Arduino Mega. Опрос 12 датчиков влажности "
  "выполняется через аналоговый мультиплексор CD74HC4067, управление — через два "
  "сдвиговых регистра 74HC595, дающие 16 выходов (12 насосов, вентилятор, лампа).")

table(
    ["Компонент", "Кол-во", "Назначение", "Интерфейс"],
    [
        ["CD74HC4067", "1", "12 датчиков влажности + LDR", "аналог (A0) + 4 адресных линии"],
        ["DHT22", "1", "температура и влажность воздуха", "1-Wire (цифровой)"],
        ["HC-SR04", "1", "уровень воды в баке", "TRIG/ECHO"],
        ["74HC595", "2", "12 насосов + вентилятор + фитолампа", "SPI-подобный (3 провода)"],
        ["Датчики влажности", "12", "по одному на участок", "через мультиплексор"],
    ],
)

p("Протокол обмена — построчный JSON по Serial на скорости 115200 бод:")
formula('Плата → сервер: {"type":"readings","tank":78.5,"data":[{"zone":1,"moisture":48,...}]}')
formula('Сервер → плата: {"cmd":"set","zone":3,"device":"watering","on":true,"seconds":10}')

p("Важное инженерное решение: сервер запускается и без реальной платы. Если не "
  "указан COM-порт, включается встроенный эмулятор — физическая модель микроклимата "
  "12 участков (испарение влаги, нагрев, освещение от времени суток, расход воды из "
  "бака). Эмулятор повторяет тот же протокол, поэтому переход на реальное железо "
  "сводится к добавлению флага --serial COM3 и не требует правок в коде.")
p("Безопасность исполнителей обеспечивается на двух уровнях: в прошивке ограничено "
  "максимальное время непрерывной работы насоса (страховка от залипания реле), а на "
  "сервере импульсный запуск автоматически снимается по таймеру.")

